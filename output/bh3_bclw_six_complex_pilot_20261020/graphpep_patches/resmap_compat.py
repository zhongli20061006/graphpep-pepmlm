#!/usr/bin/env python3
"""Corrected, pandas-3-compatible replacement for GraphPep bin/resmap.py.

Auto-generated by pipeline/make_resmap_compat.py -- do not hand-edit.

Usage (identical to the original):
    resmap_compat.py pro.pdb pro_renum.pdb pep.pdb pep_renum.pdb tmp_each.csv out.csv
"""
import sys
import pandas as pd
import MDAnalysis as mda


def build_index_to_resid_chain(pdb_path):
    """index (1-based) -> "resSeq+icode:chainID"."""
    u = mda.Universe(pdb_path)
    mapping, idx = {}, 1
    for res in u.residues:
        icode = ""
        if hasattr(res, "icode") and res.icode:
            icode = res.icode.strip()
        if hasattr(res.atoms[0], "chainID"):
            chain = res.atoms[0].chainID.strip()
        else:
            chain = res.segid.strip()
        mapping[idx] = f"{res.resid}{icode}:{chain}".replace(" ", "")
        idx += 1
    return mapping


def build_resseq_to_index(pdb_path):
    """ "resSeq+icode" -> index (1-based)."""
    u = mda.Universe(pdb_path)
    mapping, idx = {}, 1
    for res in u.residues:
        icode = ""
        if hasattr(res, "icode") and res.icode:
            icode = res.icode.strip()
        mapping[f"{res.resid}{icode}".replace(" ", "")] = idx
        idx += 1
    return mapping


def decode(value, index_to_id, resseq_to_index, label, stats):
    """Resolve a GraphPep residue field to an "<resid>:<chain>" identifier.

    Already-formatted values (defect 2) pass straight through; bare numeric values are
    resolved through the structural maps exactly as the original intended.
    """
    s = str(value).strip()
    if ":" in s:
        stats[label + "_passthrough"] += 1
        return s
    key = s[:-2] if s.endswith(".0") else s
    idx = resseq_to_index.get(key)
    if idx is None:
        stats[label + "_unresolved"] += 1
        return s
    stats[label + "_mapped"] += 1
    return index_to_id.get(idx, s)


def main():
    if len(sys.argv) != 7:
        print("usage: resmap.py pro.pdb pro_renum.pdb pep.pdb pep_renum.pdb "
              "tmp_each.csv out.csv")
        sys.exit(1)

    protein_pdb, protein_renum = sys.argv[1], sys.argv[2]
    peptide_pdb, peptide_renum = sys.argv[3], sys.argv[4]
    csv_in, csv_out = sys.argv[5], sys.argv[6]

    pnum = build_index_to_resid_chain(protein_pdb)
    prenum = build_resseq_to_index(protein_renum)
    num = build_index_to_resid_chain(peptide_pdb)
    renum = build_resseq_to_index(peptide_renum)

    df = pd.read_csv(csv_in, dtype=str)
    if df.shape[1] < 4:
        raise SystemExit(f"FATAL: expected 4 columns in {csv_in}, got {df.shape[1]}")

    stats = {"pep_passthrough": 0, "pep_mapped": 0, "pep_unresolved": 0,
             "pro_passthrough": 0, "pro_mapped": 0, "pro_unresolved": 0}

    rows = []
    for i in range(len(df)):
        r = df.iloc[i]
        decoy = r.iloc[0]
        pep_id = decode(r.iloc[1], num, renum, "pep", stats)
        pro_id = decode(r.iloc[2], pnum, prenum, "pro", stats)
        rows.append([decoy, pep_id, pro_id, r.iloc[3]])

    out = pd.DataFrame(rows, columns=["DECOY_ID", "RESID_PEP", "RESID_PRO",
                                      "CONFIDENT_SCORES"])
    out.to_csv(csv_out, index=False)

    print(f"resmap_compat: {len(out)} rows -> {csv_out}")
    print(f"  peptide ids: passthrough={stats['pep_passthrough']} "
          f"mapped={stats['pep_mapped']} unresolved={stats['pep_unresolved']}")
    print(f"  protein ids: passthrough={stats['pro_passthrough']} "
          f"mapped={stats['pro_mapped']} unresolved={stats['pro_unresolved']}")
    if stats["pep_unresolved"] or stats["pro_unresolved"]:
        print("  WARNING: some residue ids could not be resolved; they were passed through",
              file=sys.stderr)


if __name__ == "__main__":
    main()
